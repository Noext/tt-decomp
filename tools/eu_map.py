#!/usr/bin/env python3
"""Map the US decompilation's function addresses onto another build of the same game.

The US project names its functions by address (`func_00100220`, `CarIconMaker__virtual_01 = 0x...`).
In another build those addresses moved. This scans the target's function starts, pairs each with a
US function by comparing masked instruction bodies, and writes a symbol file in the US project's
format with the *target's* addresses and the *US* names.

Masking: call/jump targets and `lui` immediates that look like addresses. Struct offsets, constants
and frame sizes must match, so a pair is the same source compiled the same way.

usage: eu_map.py US_ELF TARGET_ELF [--out config/symbol_addrs.txt] [--min 4] [--jobs N]

US_ELF is the build the decomp was written for; TARGET_ELF is the one to name. Neither is modified.
"""
import argparse
import collections
import concurrent.futures
import hashlib
import os
import re
import struct
import sys


def load(path):
    d = open(path, 'rb').read()
    e_shoff, = struct.unpack_from('<I', d, 32)
    shentsize, shnum = struct.unpack_from('<HH', d, 46)
    S = [struct.unpack_from('<IIIIIIIIII', d, e_shoff + i * shentsize) for i in range(shnum)]
    secs = [dict(type=s[1], addr=s[3], off=s[4], size=s[5], flags=s[2]) for s in S]
    code = max((s for s in secs if s['type'] == 1 and s['size'] > 1 << 20), key=lambda s: s['size'])
    words = list(struct.unpack_from('<%dI' % (code['size'] // 4), d[code['off']:code['off'] + code['size']]))
    return code['addr'], words


def func_starts(base, words):
    """Every `jal` target inside the code, plus the entry point's own range."""
    out = set()
    for i, w in enumerate(words):
        if w >> 26 == 3:
            t = ((base + i * 4 + 4) & 0xF0000000) | ((w & 0x3FFFFFF) << 2)
            if base <= t < base + len(words) * 4:
                out.add(t)
    return sorted(out)


def spans(starts, base, nwords):
    out = []
    for j, s in enumerate(starts):
        nxt = starts[j + 1] if j + 1 < len(starts) else base + nwords * 4
        n = min(max(1, (nxt - s) // 4), 1024)
        out.append((s, n))
    return out


def mask(w):
    op = w >> 26
    if op in (2, 3):
        return w & 0xFC000000
    if op == 15:
        return w & 0xFFFF0000 if 0x00100000 <= ((w & 0xFFFF) << 16) <= 0x00900000 else w
    return w


def body(words, base, addr, n):
    i = (addr - base) // 4
    return tuple(mask(words[i + j]) for j in range(min(n, len(words) - i)))


def key_of(body_words, k):
    """A matching key that survives a shift of the function inside the binary."""
    return (len(body_words), body_words[:k])


def read_us_names(path):
    """name -> address from a symbol_addrs.txt in the US project's format."""
    text = open(path).read()
    names = {}
    for m in re.finditer(r'^(\w+)\s*=\s*0x([0-9A-Fa-f]+);(?:\s*//\s*type:(\w+))?', text, re.M):
        names[int(m.group(2), 16)] = (m.group(1), m.group(3) or 'func')
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('us_elf')
    ap.add_argument('target_elf')
    ap.add_argument('--us-symbols', default=None, help='the US project symbol file (names)')
    ap.add_argument('--out', default=None)
    ap.add_argument('--min', type=int, default=4, help='words that must match to pair')
    a = ap.parse_args()

    ub, uw = load(a.us_elf)
    tb, tw = load(a.target_elf)
    us = spans(func_starts(ub, uw), ub, len(uw))
    tg = spans(func_starts(tb, tw), tb, len(tw))
    print(f'US      {ub:#010x}  {len(us):>6,} functions  {len(uw):>9,} words')
    print(f'target  {tb:#010x}  {len(tg):>6,} functions  {len(tw):>9,} words')

    index = collections.defaultdict(list)
    for s, n in tg:
        k = min(n, a.min)
        index[(n, body(tw, tb, s, k))].append((s, n))

    names = read_us_names(a.us_symbols) if a.us_symbols else {}
    pairs = []            # (target address, us address, length in words, exact?)
    used = set()
    for s, n in us:
        b = body(uw, ub, s, n)
        k = min(n, a.min)
        cand = index.get((n, b[:k]), ())
        hit = None
        for s2, n2 in cand:
            if s2 in used:
                continue
            if body(tw, tb, s2, n) == b:
                exact = list(uw[(s - ub) // 4:(s - ub) // 4 + n]) == list(tw[(s2 - tb) // 4:(s2 - tb) // 4 + n])
                hit = (s2, s, n, exact)
                break
        if hit:
            used.add(hit[0])
            pairs.append(hit)

    matched = len(pairs)
    exact = sum(1 for p in pairs if p[3])
    print(f'\npaired: {matched:,} of {len(us):,} US functions '
          f'({100*matched/len(us):.1f}%); {exact:,} byte-identical ({100*exact/max(1,matched):.1f}%)')

    if not a.out:
        return
    lines = ['// EU symbol map: US decompilation names at their SCES-53372 addresses,',
             '// generated by tools/eu_map.py from the two executables. Bodies are masked-equal.',
             f'// pairs {matched} exact {exact}']
    named = 0
    for s2, s, n, is_exact in sorted(pairs, key=lambda p: p[0]):
        name, kind = names.get(s, (f'func_{s:08X}', 'func'))
        lines.append(f'{name} = 0x{s2:08X}; // type:{kind}' + ('' if is_exact else ' // masked'))
        named += kind == 'func'
    with open(a.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {a.out}: {len(pairs):,} symbols')


if __name__ == '__main__':
    main()
